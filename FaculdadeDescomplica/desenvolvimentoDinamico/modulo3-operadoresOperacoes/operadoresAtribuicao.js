// Exemplos de Operadores de Atribuição em JavaScript

// Operador de Atribuição  Básico (=)
let a = 10; // Atribui o valor 10 à variável 'a'
console.log(`O valor inicial de a: ${a}`); // Saída: O valor inicial de a: 10

// Operador de Atribuição de Adição (+=)
a += 5; // Equivalente a: a = a + 5
console.log(`Após a += 5, o valor de a: ${a}`); // Saída: Após a += 5, o valor de a: 15

// Operador de Atribuição de Subtração (-=)
a -= 3; // Equivalente a: a = a - 3
console.log(`Após a -= 3, o valor de a: ${a}`); // Saída: Após a -= 3, o valor de a: 12

// Operador de Atribuição de Multiplicação (*=)
a *= 2; // Equivalente a: a = a * 2
console.log(`Após a *= 2, o valor de a: ${a}`); // Saída: Após a *= 2, o valor de a: 24
// comparação e não atribuição: >=

// Operador de Atribuição de Divisão (/=)
a /= 4; // Equivalente a: a = a / 4
console.log(`Após a /= 4, o valor de a: ${a}`); // Saída: Após a /= 4, o valor de a

// Operador de Atribuição de Resto (%=)
a %= 4; // Equivalente a: a = a % 4
console.log(`Após a %= 4, o valor de a: ${a}`); // Saída: Após a %= 4, o valor de a: 0

// Operador de Atribuição de Exponenciação (**=)
a **= 3; // Equivalente a: a = a ** 3
console.log(`Após a **= 3, o valor de a: ${a}`); // Saída: Após a **= 3, o valor de a: 0